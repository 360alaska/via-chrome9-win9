#!/usr/bin/env python3
"""hal_asm.py (.545): the HAL's span kernels for the indexed pass-through (src/vx_hal_sse.asm, Open Watcom wasm).

As tools/tnl_asm.py (whose assemble and wasm this uses): Intel syntax, assembled for i686 with no relocations, written out as `db` bytes
with the mnemonic as a comment. Each kernel is cdecl with one argument, the vxs_frame (vxs_max16: the indices and their count) of src/vx_d3d_span.inc (offsets below, checked there
by VXS_OFF under Watcom). tests/test_hal_asm.c runs the bytes against the C reference (vxs_check_c, vxs_conv_c) on random spans.

  python3 tools/hal_asm.py            writes src/vx_hal_sse.asm and tests/hal_kernels.s
"""
import sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parent))
from tnl_asm import assemble,wasm,ROOT
F={'vb':0,'stride':4,'n':8,'w':12,'wstride':16,'coff':20,'smode':24,'soff':28,'t0':32,'v0on':36,'two':40,'t1':44,'v1on':48,
 'kbias':96,'kgu':112,'kz':128,'kw':144,'kone':160,'kneg0':176,'kxlo':192,'kxr':208,'kylo':224,'kyr':240,'kxg':256,'kyg':272}
def axis(r,lo,rng,g):
 # fail lanes of one axis (GB_IN) or'd into xmm6: out = (a - lo) ^ bias > range ^ bias; the guard's alternative: a negative, a <= 0xBF000000
 return f"""
 movdqu xmm7,[ebp+{F['kbias']}]
 pxor xmm7,{r}
 movdqu xmm1,[ebp+{F['kgu']}]
 pcmpgtd xmm7,xmm1
 movdqa xmm3,{r}
 psrad xmm3,31
 pandn xmm7,xmm3
 movdqu xmm1,[ebp+{F[g]}]
 pand xmm7,xmm1
 movdqu xmm1,[ebp+{F[lo]}]
 movdqa xmm3,{r}
 psubd xmm3,xmm1
 movdqu xmm1,[ebp+{F['kbias']}]
 pxor xmm3,xmm1
 movdqu xmm1,[ebp+{F[rng]}]
 pcmpgtd xmm3,xmm1
 pandn xmm7,xmm3
 por xmm6,xmm7"""
CHECK=f"""
_vxs_check:
 push ebx
 push esi
 push edi
 push ebp
 mov ebp,[esp+20]
 mov esi,[ebp+{F['vb']}]
 mov ebx,[ebp+{F['stride']}]
 mov ecx,[ebp+{F['n']}]
 xor eax,eax
1:
 mov edx,ecx
 sub edx,eax
 cmp edx,4
 jb 9f
 mov edx,esi
 movdqu xmm0,[edx]
 add edx,ebx
 movdqu xmm1,[edx]
 add edx,ebx
 movdqu xmm2,[edx]
 add edx,ebx
 movdqu xmm3,[edx]
 movaps xmm4,xmm0
 unpcklps xmm0,xmm1
 unpckhps xmm4,xmm1
 movaps xmm5,xmm2
 unpcklps xmm2,xmm3
 unpckhps xmm5,xmm3
 movaps xmm1,xmm0
 movlhps xmm0,xmm2
 movhlps xmm2,xmm1
 movaps xmm3,xmm4
 movlhps xmm4,xmm5
 movhlps xmm5,xmm3
 pxor xmm6,xmm6
{axis('xmm0','kxlo','kxr','kxg')}
{axis('xmm2','kylo','kyr','kyg')}
 movdqu xmm1,[ebp+{F['kbias']}]
 movdqa xmm3,xmm4
 pxor xmm3,xmm1
 movdqu xmm1,[ebp+{F['kz']}]
 pcmpgtd xmm3,xmm1
 por xmm6,xmm3
 movdqu xmm1,[ebp+{F['kone']}]
 movdqa xmm3,xmm5
 psubd xmm3,xmm1
 movdqu xmm1,[ebp+{F['kbias']}]
 pxor xmm3,xmm1
 movdqu xmm1,[ebp+{F['kw']}]
 pcmpgtd xmm1,xmm3
 pcmpeqd xmm3,xmm3
 pxor xmm1,xmm3
 por xmm6,xmm1
 movmskps edi,xmm6
 test edi,edi
 jnz 8f
 lea esi,[esi+ebx*4]
 add eax,4
 jmp 1b
8:
 bsf edi,edi
 add eax,edi
9:
 pop ebp
 pop edi
 pop esi
 pop ebx
 ret
"""
def fin(r):
 # a coordinate word not finite as 0 (edx the scratch)
 return f"""
 mov edx,{r}
 and edx,0x7F800000
 cmp edx,0x7F800000
 jne 5f
 xor {r},{r}
5:"""
CONV=f"""
_vxs_conv:
 push ebx
 push esi
 push edi
 push ebp
 mov ebp,[esp+20]
 mov esi,[ebp+{F['vb']}]
 mov edi,[ebp+{F['w']}]
 mov ecx,[ebp+{F['n']}]
 test ecx,ecx
 jz 9f
 movdqu xmm7,[ebp+{F['kneg0']}]
1:
 movdqu xmm0,[esi]
 movdqa xmm1,xmm0
 pcmpeqd xmm1,xmm7
 pandn xmm1,xmm0
 movdqu [edi],xmm1
 mov edx,[ebp+{F['coff']}]
 mov eax,-1
 test edx,edx
 jz 2f
 mov eax,[esi+edx]
2:
 mov [edi+16],eax
 mov edx,[ebp+{F['smode']}]
 xor eax,eax
 cmp edx,1
 jb 3f
 mov eax,0xFF000000
 je 3f
 mov edx,[ebp+{F['soff']}]
 mov eax,[esi+edx]
3:
 mov [edi+20],eax
 xor eax,eax
 xor ebx,ebx
 mov edx,[ebp+{F['t0']}]
 test edx,edx
 jz 4f
 mov eax,[esi+edx]
 cmp dword ptr [ebp+{F['v0on']}],0
 je 6f
 mov ebx,[esi+edx+4]
6:{fin('eax')}{fin('ebx')}
4:
 mov [edi+24],eax
 mov [edi+28],ebx
 cmp dword ptr [ebp+{F['two']}],0
 je 7f
 xor eax,eax
 xor ebx,ebx
 mov edx,[ebp+{F['t1']}]
 test edx,edx
 jz 7f
 mov eax,[esi+edx]
 cmp dword ptr [ebp+{F['v1on']}],0
 je 6f
 mov ebx,[esi+edx+4]
6:{fin('eax')}{fin('ebx')}
7:
 mov [edi+32],eax
 mov [edi+36],ebx
 add esi,[ebp+{F['stride']}]
 add edi,[ebp+{F['wstride']}]
 dec ecx
 jnz 1b
9:
 pop ebp
 pop edi
 pop esi
 pop ebx
 ret
"""
MAX16="""
_vxs_max16:
 push esi
 mov esi,[esp+8]
 mov ecx,[esp+12]
 pcmpeqw xmm1,xmm1
 psllw xmm1,15
 movdqa xmm0,xmm1
1:
 cmp ecx,8
 jb 2f
 movdqu xmm2,[esi]
 pxor xmm2,xmm1
 pmaxsw xmm0,xmm2
 add esi,16
 sub ecx,8
 jmp 1b
2:
 pshufd xmm2,xmm0,0x4E
 pmaxsw xmm0,xmm2
 pshufd xmm2,xmm0,0xB1
 pmaxsw xmm0,xmm2
 pshuflw xmm2,xmm0,0xB1
 pmaxsw xmm0,xmm2
 pxor xmm0,xmm1
 movd eax,xmm0
 and eax,0xFFFF
3:
 test ecx,ecx
 jz 9f
 movzx edx,word ptr [esi]
 cmp edx,eax
 jbe 4f
 mov eax,edx
4:
 add esi,2
 dec ecx
 jmp 3b
9:
 pop esi
 ret
"""
def main():
 chk=assemble('_vxs_check',CHECK);cnv=assemble('_vxs_conv',CONV);mx=assemble('_vxs_max16',MAX16)
 text='; vx_hal_sse.asm: the HAL\'s span kernels for the indexed pass-through (SSE2) as bytes for wasm. GENERATED by tools/hal_asm.py: edit that file, not this.\n'\
  '; cdecl, one argument (the vxs_frame of src/vx_d3d_span.inc); the C reference there (vxs_check_c, vxs_conv_c) gives the same results.\n'\
  '.386\n.model flat\n.code\n'+wasm('_vxs_check',chk)+'\n'+wasm('_vxs_conv',cnv)+'\n'+wasm('_vxs_max16',mx)+'\nend\n'
 (ROOT/'src'/'vx_hal_sse.asm').write_text(text)
 (ROOT/'tests'/'hal_kernels.s').write_text(".intel_syntax noprefix\n.text\n.globl _vxs_check\n.globl _vxs_conv\n.globl _vxs_max16\n"+CHECK+CONV+MAX16)
 print('vxs_check %d bytes, %d instructions; vxs_conv %d bytes, %d instructions'%(sum(len(b) for b,_ in chk),len(chk),sum(len(b) for b,_ in cnv),len(cnv)))
if __name__=='__main__':main()
