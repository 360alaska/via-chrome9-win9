#!/usr/bin/env python3
"""v10.342: GLTRACE's generated tables (src/gltrace_gen.h): every OpenGL 1.1 entry point of opengl32.dll (from gl/mesa/include/GL/gl.h)
plus the extension entry points Quake 2 asks for, with how each argument and each pointed-to block is recorded and replayed.
Used by src/gltrace.c (the recording OPENGL32.DLL) and src/glreplay.c (the replay, Win98 EXE and host model)."""
import re,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
src=(ROOT/'gl/mesa/include/GL/gl.h').read_text()
src=src[:src.index(' * OpenGL 1.2')]
protos=[]
for m in re.finditer(r'GLAPI\s+([\w\s\*]+?)\s*GLAPIENTRY\s+(gl\w+)\s*\(([^;]*?)\)\s*;',src,re.S):
    ret=' '.join(m.group(1).split());name=m.group(2);args=' '.join(m.group(3).split())
    protos.append((ret,name,args))
EXT=[('void','glPointParameterfEXT','GLenum pname, GLfloat param'),('void','glPointParameterfvEXT','GLenum pname, const GLfloat *params'),
     ('void','glColorTableEXT','GLenum target, GLenum internalformat, GLsizei width, GLenum format, GLenum type, const GLvoid *table'),
     ('void','glSelectTextureSGIS','GLenum target'),('void','glMTexCoord2fSGIS','GLenum target, GLfloat s, GLfloat t'),
     ('void','glActiveTextureARB','GLenum texture'),('void','glClientActiveTextureARB','GLenum texture'),('void','glMultiTexCoord2fARB','GLenum target, GLfloat s, GLfloat t'),
     ('void','glLockArraysEXT','GLint first, GLsizei count'),('void','glUnlockArraysEXT','void')]
def params(a):
    if a.strip()=='void':return []
    out=[]
    for p in a.split(','):
        p=p.strip();m=re.match(r'(.*?)(\w+)$',p);t=' '.join(m.group(1).replace('*',' * ').split());out.append((t,m.group(2)))
    return out
TS={'b':1,'s':2,'i':4,'f':4,'d':8,'ub':1,'us':2,'ui':4}
def kind(t):
    if '*' in t:return 'p'
    if t in('GLdouble','GLclampd'):return 'd'
    if t in('GLfloat','GLclampf'):return 'f'
    return 'i'
def blob(name,ps,pi):
    """size expression (C, in the proxy's argument names) of pointer argument pi, or None (output or not recorded)"""
    pn=ps[pi][1];t=ps[pi][0]
    if 'const' not in t:return None
    m=re.match(r'gl(Vertex|Color|TexCoord|Normal|RasterPos|Index|EvalCoord)([1-4])?(ub|us|ui|b|s|i|f|d)v$',name)
    if m:
        n={'Normal':3,'Index':1}.get(m.group(1),int(m.group(2) or 1));return str(n*TS[m.group(3)])
    m=re.match(r'glRect(s|i|f|d)v$',name)
    if m:return str(2*TS[m.group(1)])
    if name=='glEdgeFlagv':return '1'
    if re.match(r'gl(Load|Mult)Matrix[fd]$',name):return '128' if name.endswith('d') else '64'
    if name=='glClipPlane':return '32'
    if name in('glTexImage2D','glTexSubImage2D','glDrawPixels'):return 'gt_img(width,height,format,type)'
    if name in('glTexImage1D','glTexSubImage1D'):return 'gt_img(width,1,format,type)'
    if name=='glColorTableEXT':return 'gt_img(width,1,format,type)'
    if name in('glDeleteTextures',):return 'n*4'
    if name=='glPrioritizeTextures':return 'n*4'
    if name=='glPolygonStipple':return '128'
    if name=='glBitmap':return 'gt_img(width,height,0x1900,0x1A00)'
    if name=='glCallLists':return 'gt_lists(n,type)'
    m=re.match(r'gl(TexParameter|TexEnv|Fog|Light|LightModel|Material|TexGen|PointParameter)(f|i|d)v(EXT)?$',name)
    if m:return 'gt_pcount(pname)*%d'%(8 if m.group(2)=='d' else 4)
    m=re.match(r'glPixelMap(fv|uiv|usv)$',name)
    if m:return 'mapsize*%d'%(2 if m.group(1)=='usv' else 4)
    return None
GEOM=re.compile(r'gl(Begin|End|Vertex\w*|TexCoord\w*|Normal\w*|EdgeFlag|EdgeFlagv|Index[a-z]+v?|EvalCoord\w*|EvalPoint\w*|Rect\w*|ArrayElement|MTexCoord2fSGIS|MultiTexCoord2fARB)$')
UNSUP=set(['glVertexPointer','glColorPointer','glTexCoordPointer','glNormalPointer','glIndexPointer','glEdgeFlagPointer','glInterleavedArrays','glDrawArrays','glDrawElements','glArrayElement','glMap1d','glMap1f','glMap2d','glMap2f','glNewList','glEndList','glCallList','glCallLists'])
SKIPREPLAY=re.compile(r'gl(Get\w+|IsEnabled|IsList|IsTexture|AreTexturesResident|ReadPixels|RenderMode|SelectBuffer|FeedbackBuffer|Finish|Flush|GenLists|DeleteLists)$')
allf=[(r,n,a,0) for r,n,a in protos]+[(r,n,a,1) for r,n,a in EXT]
o=['/* generated by tools/gltrace_gen.py: do not edit */','#define GT_NFUNCS %d'%len(allf)]
names=[];
for i,(r,n,a,ext) in enumerate(allf):
    ps=params(a);cls=('G' if GEOM.match(n) else 'U' if n in UNSUP else 'S' if n.startswith('glTexSubImage') else 'Q' if SKIPREPLAY.match(n) else 'N')
    names.append('{"%s",\'%s\',%d}'%(n,cls,ext))
o.append('static const struct gt_fn {const char *name;char cls;char ext;} gt_fns[GT_NFUNCS]={'+',\n'.join(names)+'};')
# the proxy's wrappers
o.append('#ifdef GT_PROXY')
for i,(r,n,a,ext) in enumerate(allf):
    ps=params(a);args=', '.join(p[1] for p in ps)
    o.append('static %s (WINAPI *r_%s)(%s);'%(r,n,a))
for i,(r,n,a,ext) in enumerate(allf):
    ps=params(a);args=', '.join(p[1] for p in ps)
    body=['if(gt_rec(%d)){'%i]
    for pi,(t,pn) in enumerate(ps):
        k=kind(t)
        if k=='i':body.append('gt_i((unsigned long)%s);'%pn)
        elif k=='f':body.append('gt_f(%s);'%pn)
        elif k=='d':body.append('gt_d(%s);'%pn)
    for pi,(t,pn) in enumerate(ps):
        if kind(t)=='p':
            sz=blob(n,ps,pi);body.append('gt_blob(%s,%s);'%(pn,sz if sz else '0') if sz else 'gt_blob(0,0xFFFFFFFFUL);')
    body.append('gt_done();}')
    call='r_%s(%s)'%(n,args)
    post=''
    if n=='glGenTextures':post='gt_gen(n,textures);'
    if n=='glPixelStorei':post='gt_store(pname,(long)param);'
    if n=='glPixelStoref':post='gt_store(pname,(long)param);'
    if r=='void':o.append('%s WINAPI gt_%s(%s) {%s %s;%s}'%(r,n,a,''.join(body),call,post))
    else:o.append('%s WINAPI gt_%s(%s) {%s rv;%s rv=%s;%sreturn rv;}'%(r,n,a,r,''.join(body),call,post))
o.append('static void *gt_wrap[GT_NFUNCS]={'+','.join('(void*)gt_%s'%n for r,n,a,e in allf)+'};')
o.append('static void **gt_real[GT_NFUNCS]={'+','.join('(void**)&r_%s'%n for r,n,a,e in allf)+'};')
o.append('#endif')
# the replay's calls
o.append('#ifdef GT_REPLAY')
for i,(r,n,a,ext) in enumerate(allf):o.append('typedef %s (GT_API *t_%s)(%s);'%(r,n,a))
o.append('static void gt_call(int id,void **fp) {switch(id){')
for i,(r,n,a,ext) in enumerate(allf):
    ps=params(a);vals=[]
    pre=[]
    for pi,(t,pn) in enumerate(ps):
        k=kind(t)
        if k=='i':pre.append('unsigned long a%d=rd_i();'%pi);vals.append('(%s)a%d'%(t,pi))
        elif k=='f':pre.append('float a%d=rd_f();'%pi);vals.append('a%d'%pi)
        elif k=='d':pre.append('double a%d=rd_d();'%pi);vals.append('a%d'%pi)
    for pi,(t,pn) in enumerate(ps):
        if kind(t)=='p':pre.append('void *a%d=rd_blob();'%pi);vals.append('(%s)a%d'%(t,pi))
    if n=='glGenTextures':pre.append('rd_skipgen();')
    o.append(' case %d:{%s if(fp[%d])((t_%s)fp[%d])(%s);break;}'%(i,''.join(pre),i,n,i,', '.join(vals)))
o.append(' }}')
o.append('#endif')
# export list for wlink
exps=[]
for r,n,a,ext in allf:
    if ext:continue
    ps=params(a);bytes_=sum(8 if kind(t)=='d' else 4 for t,_ in ps);exps.append((n,bytes_))
(ROOT/'src'/'gltrace_gen.h').write_text('\n'.join(o)+'\n')
(ROOT/'src'/'gltrace_exports.txt').write_text(''.join('%s %d\n'%e for e in exps))
print(len(allf),'functions,',len(exps),'exports')
