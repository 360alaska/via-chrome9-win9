#!/usr/bin/env python3
"""Generate src/vx_xp_programs.h from the CLXP3D captures of Windows XP's driver (captures/clxp3d_2026-10-22).
Each entry is the ALU program (block 20030000), its instruction count and the TAU words (block 21030000) XP sent for one case."""
import os,sys
here=os.path.dirname(os.path.abspath(__file__));sys.path.insert(0,here)
from dec import case_packets
root=os.path.dirname(here);cap=os.path.join(root,'captures','clxp3d_2026-10-22')
CASES=[('TEX','T00','colour and alpha = texture'),('DIFF','T13','colour and alpha = diffuse'),('MOD_BOTH','T02','MODULATE texture x diffuse, colour and alpha'),
 ('MOD','T01','colour MODULATE texture x diffuse, alpha = texture'),('MOD2X','T07','MODULATE2X, alpha = texture'),('MOD4X','T08','MODULATE4X, alpha = texture'),
 ('ADD','T06','ADD texture + diffuse, alpha = texture'),('ADDSIGNED','T09','ADDSIGNED, alpha = texture'),('BLEND_TA','T10','BLENDTEXTUREALPHA(texture, diffuse), alpha = texture'),
 ('BLEND_DA','T11','BLENDDIFFUSEALPHA(texture, diffuse), alpha = texture'),('MOD_TF','T12','MODULATE texture x TFACTOR (constant c2), alpha = texture'),
 ('TEX_DIFFA','T04','colour = texture, alpha = diffuse'),('DIFF_TEXA','T05','colour = diffuse, alpha = texture'),
 ('DIFF_SPEC','T14','diffuse + specular, alpha = diffuse'),('MOD_SPEC','T15','MODULATE texture x diffuse + specular, alpha = texture')]
out=['/* Generated by tools/gen_xp_programs.py from the CLXP3D captures of the Windows XP driver; do not edit. */','#ifndef VX_XP_PROGRAMS_H','#define VX_XP_PROGRAMS_H']
names=[]
for i,(key,case,desc) in enumerate(CASES):
    ps=case_packets(os.path.join(cap,case+'.RNG'))
    alu=[p for p in ps if p[0]=='blk' and p[1]==0x20030000]
    tau=[p for p in ps if p[0]=='blk' and p[1]==0x21030000]
    assert alu,case
    w=alu[0][2];assert len(w)%4==0 and 4<=len(w)<=12,(case,len(w))
    names.append(key)
    out.append('#define VX_XP_%s %d /* %s: %s */'%(key,i,case,desc))
out.append('#define VX_XP_COUNT %d'%len(CASES))
out.append('typedef struct vx_xp_program {unsigned long count,words[12],tau;} vx_xp_program;')
out.append('static const vx_xp_program vx_xp_programs[VX_XP_COUNT]={')
for key,case,desc in CASES:
    ps=case_packets(os.path.join(cap,case+'.RNG'))
    w=[p for p in ps if p[0]=='blk' and p[1]==0x20030000][0][2]
    tau=[p for p in ps if p[0]=='blk' and p[1]==0x21030000]
    t=tau[0][2][0] if tau else 0
    out.append(' {%d,{%s},0x%08XUL}, /* %s */'%(len(w)//4,','.join('0x%08XUL'%x for x in w+[0]*(12-len(w))),t,case))
out.append('};')
# the 20-word table XP loads once at setup as block 12030000 (T00; also in s3ginv.dll at VA 0x2BE90)
t=[p for p in case_packets(os.path.join(cap,'T00.RNG')) if p[0]=='blk' and p[1]==0x12030000][0][2]
assert len(t)==20
out.append('static const unsigned long vx_xp_table_1203[20]={%s}; /* T00 block 12030000 */'%','.join('0x%08XUL'%x for x in t))
out.append('#endif')
open(os.path.join(root,'src','vx_xp_programs.h'),'w').write('\n'.join(out)+'\n')
print('wrote',len(CASES),'programs')
