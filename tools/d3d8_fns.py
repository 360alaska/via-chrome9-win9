# .534: writes src/vx_d3d8_fns.h, the function entries of the board's D3D8.DLL (4.09.00.0904, PE time 40EE6B0D, image 137000) for
# VXD3DMON's line report. Entries: every direct call target in .text, and every 16-byte-aligned instruction after int3/nop padding or
# after a ret/jmp (the compiler starts functions there). Usage: python3 tools/d3d8_fns.py D3D8.DLL (needs objdump).
import re,struct,subprocess,sys
dll=sys.argv[1];d=open(dll,'rb').read();pe=struct.unpack_from('<I',d,0x3c)[0]
ts=struct.unpack_from('<I',d,pe+8)[0];size=struct.unpack_from('<I',d,pe+24+56)[0];base=struct.unpack_from('<I',d,pe+24+28)[0]
asm=subprocess.run(['objdump','-d','-M','intel',dll],capture_output=True,text=True).stdout
ins=[];calls=set()
for l in asm.splitlines():
    m=re.match(r'\s+([0-9a-f]+):\t(?:[0-9a-f]{2} )+\s*\t?(.*)',l)
    if not m:continue
    a=int(m.group(1),16);t=m.group(2).strip();ins.append((a,t))
    c=re.match(r'call +0x([0-9a-f]+)$',t)
    if c:calls.add(int(c.group(1),16))
lo,hi=ins[0][0],ins[-1][0];ent={a for a in calls if lo<=a<=hi}
for i in range(2,len(ins)):
    a,t=ins[i];pt=ins[i-1][1]
    if a%16:continue
    if pt.startswith('int3'):ent.add(a)
    elif pt.startswith(('nop','lea    esi','lea    edi'))and re.match(r'(ret|jmp)',ins[i-2][1]):ent.add(a)
    elif re.match(r'(ret|jmp )',pt)and not t.startswith(('int3','nop')):ent.add(a)
r=sorted(e-base for e in ent)
o=open('src/vx_d3d8_fns.h','w')
o.write('/* .534: generated by tools/d3d8_fns.py from the board\'s D3D8.DLL: its function entries as offsets from the base (RVAs), for VXD3DMON */\n')
o.write('#define VX_D3D8_TIME 0x%08XUL\n#define VX_D3D8_SIZE 0x%XUL\n#define VX_D3D8_NFN %d\n'%(ts,size,len(r)))
o.write('static const unsigned long vx_d3d8_fn[VX_D3D8_NFN]={\n')
for i in range(0,len(r),16):o.write(','.join('0x%X'%x for x in r[i:i+16])+(',\n' if i+16<len(r) else '\n'))
o.write('};\n');o.close();print(len(r),'entries')
